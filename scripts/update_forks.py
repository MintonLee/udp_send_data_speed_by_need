#!/usr/bin/env python3
"""
update_forks.py — record this repo's fork count over time.

What it does
  1. Detects the GitHub owner/repo (from $GITHUB_REPOSITORY, else `git remote origin`).
  2. Fetches the current fork count from the GitHub REST API.
  3. Appends today's count to data/forks_history.csv (same-day rows are updated in place).
  4. Rewrites the FORK_HISTORY table (between the HTML markers) in README.md / README.zh-CN.md.

Stdlib only — no third-party dependencies. Safe to run locally or in GitHub Actions.

Usage
  python3 scripts/update_forks.py
"""

import csv
import datetime
import json
import os
import re
import subprocess
import sys
import urllib.request

# --- paths (relative to repo root; the workflow checks out at the root) ---
REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CSV_PATH = os.path.join(REPO_ROOT, "data", "forks_history.csv")
README_FILES = ["README.md", "README.zh-CN.md"]

BEGIN = "<!-- BEGIN FORK_HISTORY"
BEGIN_LINE = ("<!-- BEGIN FORK_HISTORY (auto-generated by scripts/update_forks.py "
              "— do not edit manually) -->")
END = "<!-- END FORK_HISTORY -->"
MAX_ROWS = 30          # number of most-recent rows rendered in the README table
API_URL = "https://api.github.com/repos/{}/{}"


def detect_slug():
    """Return 'owner/repo', or None if it cannot be determined."""
    slug = os.environ.get("GITHUB_REPOSITORY")
    if slug and "/" in slug:
        return slug
    try:
        url = subprocess.check_output(
            ["git", "-C", REPO_ROOT, "remote", "get-url", "origin"],
            text=True, stderr=subprocess.DEVNULL).strip()
        m = re.search(r"[:/]([^/:]+/[^/]+?)(?:\.git)?$", url)
        if m:
            return m.group(1)
    except Exception:
        pass
    return None


def fetch_forks(slug):
    owner, repo = slug.split("/", 1)
    req = urllib.request.Request(
        API_URL.format(owner, repo),
        headers={"Accept": "application/vnd.github+json",
                 "User-Agent": "fork-tracker"})
    token = os.environ.get("GITHUB_TOKEN")
    if token:
        req.add_header("Authorization", "Bearer " + token)
    with urllib.request.urlopen(req, timeout=20) as resp:
        return int(json.load(resp)["forks_count"])


def load_history():
    rows = []
    if os.path.exists(CSV_PATH):
        with open(CSV_PATH, newline="", encoding="utf-8") as f:
            for row in csv.DictReader(f):
                d, c = (row.get("date") or "").strip(), (row.get("forks") or "").strip()
                if d and c.isdigit():
                    rows.append((d, int(c)))
    return rows


def save_history(rows):
    os.makedirs(os.path.dirname(CSV_PATH), exist_ok=True)
    with open(CSV_PATH, "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["date", "forks"])
        w.writerows(rows)


def upsert(rows, date, forks):
    if rows and rows[-1][0] == date:
        rows[-1] = (date, forks)      # same day → update in place
    else:
        rows.append((date, forks))
    return rows


def render_table(rows):
    shown = rows[-MAX_ROWS:]
    lines = [BEGIN_LINE, "| Date | Forks |", "|------|-------|"]
    if not shown:
        lines.append("| _awaiting first scheduled run_ | - |")
    else:
        for d, c in shown:
            lines.append("| {} | {} |".format(d, c))
    lines.append(END)
    return "\n".join(lines)


def update_readme(path, table):
    if not os.path.exists(path):
        return False
    with open(path, encoding="utf-8") as f:
        txt = f.read()
    pattern = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END), re.S)
    if not pattern.search(txt):
        return False
    # use a function replacement so backslashes/slashes in the table stay literal
    txt = pattern.sub(lambda _m: table, txt, count=1)
    with open(path, "w", encoding="utf-8") as f:
        f.write(txt)
    return True


def main():
    slug = detect_slug()
    if not slug:
        print("Could not detect owner/repo. Set GITHUB_REPOSITORY or configure a "
              "git remote 'origin'.", file=sys.stderr)
        return 1
    try:
        forks = fetch_forks(slug)
    except Exception as e:  # noqa: BLE001
        print("Failed to fetch fork count for {}: {}".format(slug, e), file=sys.stderr)
        return 1

    today = datetime.date.today().isoformat()
    rows = upsert(load_history(), today, forks)
    save_history(rows)

    table = render_table(rows)
    for name in README_FILES:
        p = os.path.join(REPO_ROOT, name)
        if update_readme(p, table):
            print("Updated FORK_HISTORY in", name)

    print("{}: forks={} on {}".format(slug, forks, today))
    return 0


if __name__ == "__main__":
    sys.exit(main())
